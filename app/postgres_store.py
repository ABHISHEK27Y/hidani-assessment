"""PostgreSQL state for hosts whose application filesystem is temporary."""
from __future__ import annotations

import json
import os
import uuid
from contextlib import contextmanager
from datetime import datetime, timezone

import psycopg
from psycopg.rows import dict_row


def _connect():
    return psycopg.connect(os.environ["DATABASE_URL"], row_factory=dict_row, connect_timeout=10)


@contextmanager
def connect():
    with _connect() as db:
        yield db


def _now():
    return datetime.now(timezone.utc).isoformat()


def init_db():
    with _connect() as db:
        db.execute("""CREATE TABLE IF NOT EXISTS sessions (
            id TEXT PRIMARY KEY, profile_json TEXT,
            filters_json TEXT NOT NULL DEFAULT '{}',
            last_jobs_json TEXT NOT NULL DEFAULT '[]', updated_at TEXT NOT NULL)""")
        db.execute("""CREATE TABLE IF NOT EXISTS applications (
            session_id TEXT NOT NULL REFERENCES sessions(id), job_id TEXT NOT NULL,
            status TEXT NOT NULL CHECK(status IN ('awaiting_submission','submitted')),
            applied_at TEXT NOT NULL, updated_at TEXT NOT NULL,
            created_at TEXT, submitted_at TEXT,
            delivery TEXT NOT NULL DEFAULT 'assisted', receipt TEXT,
            PRIMARY KEY(session_id, job_id))""")
        db.execute("""CREATE TABLE IF NOT EXISTS messages (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            session_id TEXT NOT NULL REFERENCES sessions(id),
            role TEXT NOT NULL CHECK(role IN ('user','assistant')),
            content TEXT NOT NULL, created_at TEXT NOT NULL, payload_json TEXT)""")
        db.execute("CREATE INDEX IF NOT EXISTS messages_session ON messages(session_id, id)")
        for table, name, definition in (
            ("applications", "created_at", "TEXT"),
            ("applications", "submitted_at", "TEXT"),
            ("applications", "delivery", "TEXT NOT NULL DEFAULT 'assisted'"),
            ("applications", "receipt", "TEXT"),
            ("messages", "payload_json", "TEXT"),
        ):
            db.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {name} {definition}")
        db.execute("UPDATE applications SET created_at=applied_at WHERE created_at IS NULL")
        db.execute("UPDATE applications SET submitted_at=updated_at, applied_at=updated_at "
                   "WHERE status='submitted' AND submitted_at IS NULL")


def session(session_id: str):
    with _connect() as db:
        db.execute("INSERT INTO sessions(id, updated_at) VALUES (%s, %s) ON CONFLICT (id) DO NOTHING",
                   (session_id, _now()))
        row = db.execute("SELECT * FROM sessions WHERE id=%s", (session_id,)).fetchone()
    return {"profile": json.loads(row["profile_json"]) if row["profile_json"] else None,
            "filters": json.loads(row["filters_json"]), "last_jobs": json.loads(row["last_jobs_json"])}


def update_session(session_id: str, **fields):
    allowed = {"profile": "profile_json", "filters": "filters_json", "last_jobs": "last_jobs_json"}
    if set(fields) - set(allowed):
        raise ValueError("Unknown session field")
    if not fields:
        return
    values = {allowed[key]: json.dumps(value) if value is not None else None for key, value in fields.items()}
    clauses = ", ".join(f"{key}=%s" for key in values)
    with _connect() as db:
        db.execute(f"UPDATE sessions SET {clauses}, updated_at=%s WHERE id=%s",
                   (*values.values(), _now(), session_id))


def add_message(session_id: str, role: str, content: str, payload: dict | None = None):
    with _connect() as db:
        db.execute("INSERT INTO messages(session_id,role,content,created_at,payload_json) VALUES (%s,%s,%s,%s,%s)",
                   (session_id, role, content[:4000], _now(), json.dumps(payload) if payload else None))
        db.execute("DELETE FROM messages WHERE session_id=%s AND id NOT IN "
                   "(SELECT id FROM messages WHERE session_id=%s ORDER BY id DESC LIMIT 200)",
                   (session_id, session_id))


def history(session_id: str, limit=40):
    with _connect() as db:
        rows = db.execute("SELECT id, role, content, created_at, payload_json FROM messages "
                          "WHERE session_id=%s ORDER BY id DESC LIMIT %s", (session_id, limit)).fetchall()
    return [{"id": row["id"], "role": row["role"], "content": row["content"],
             "created_at": row["created_at"],
             "payload": json.loads(row["payload_json"]) if row["payload_json"] else None}
            for row in reversed(rows)]


def create_application(session_id: str, job_id: str, mode="assisted"):
    now = _now()
    simulated = mode == "simulation"
    receipt = "SIM-" + uuid.uuid4().hex[:12].upper() if simulated else None
    with _connect() as db:
        row = db.execute("""INSERT INTO applications
            (session_id,job_id,status,applied_at,updated_at,created_at,submitted_at,delivery,receipt)
            VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s)
            ON CONFLICT (session_id,job_id) DO NOTHING RETURNING job_id""",
            (session_id, job_id, "submitted" if simulated else "awaiting_submission",
             now, now, now, now if simulated else None, mode, receipt)).fetchone()
        application = db.execute("SELECT * FROM applications WHERE session_id=%s AND job_id=%s",
                                 (session_id, job_id)).fetchone()
    return {**application, "duplicate": row is None}


def confirm_application(session_id: str, job_id: str):
    now = _now()
    with _connect() as db:
        db.execute("UPDATE applications SET status='submitted', applied_at=%s, submitted_at=%s, updated_at=%s "
                   "WHERE session_id=%s AND job_id=%s AND status='awaiting_submission'",
                   (now, now, now, session_id, job_id))
        row = db.execute("SELECT * FROM applications WHERE session_id=%s AND job_id=%s",
                         (session_id, job_id)).fetchone()
    return row


def applications(session_id: str):
    with _connect() as db:
        return db.execute("SELECT * FROM applications WHERE session_id=%s ORDER BY created_at DESC",
                          (session_id,)).fetchall()


def delete_session(session_id: str):
    with _connect() as db:
        for table in ("messages", "applications", "sessions"):
            column = "id" if table == "sessions" else "session_id"
            db.execute(f"DELETE FROM {table} WHERE {column}=%s", (session_id,))
